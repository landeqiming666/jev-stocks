test("inbox_old_request_cannot_overwrite_new_response", async () => {
  const fake = testClient(), old = deferred<Inbox>(), latest = deferred<Inbox>();
  fake.call.mockImplementationOnce(() => old.promise).mockImplementationOnce(() => latest.promise);
  const hook = renderHook(() => useInbox(fake.client));
  let request!: Promise<void>;
  act(() => { request = hook.result.current.refresh(); });
  const empty = example<Inbox>("inbox.list", "empty"); latest.resolve(empty);
  await act(() => request);
  await act(async () => old.resolve(pendingInbox()));
  expect(hook.result.current.inbox).toEqual(empty);
});
