test("inbox_same_decision_action_is_deduplicated_and_whitespace_stored_as_null", async () => {
  const fake = testClient(), saved = deferred<DecisionSummary>();
  const hook = renderHook(() => useInbox(fake.client));
  await waitFor(() => expect(hook.result.current.state).toBe("ready"));
  const first = pendingInbox().items[0]!;
  fake.call.mockImplementationOnce(() => saved.promise);
  let one!: Promise<void>, two!: Promise<void>;
  act(() => { one = hook.result.current.act(first.decisionId, "still_valid", "  "); two = hook.result.current.act(first.decisionId, "ignore"); });
  expect(one).toBe(two);
  expect(hook.result.current.inbox!.items).toHaveLength(2);
  saved.resolve({ ...first, action: { action: "still_valid", note: null, actedAt: pendingInbox().asOf } });
  await act(() => one);
  expect(fake.call.mock.calls.filter(([method]) => method === "decision.act")).toHaveLength(1);
  expect(fake.call).toHaveBeenCalledWith("decision.act", { decisionId: first.decisionId, action: "still_valid", note: null }, expect.any(Object));
});
test("inbox_rollback_one_action_preserves_other_committed_action_and_original_object", async () => {
  const initial = pendingInbox(), fake = testClient(initial), a = deferred<DecisionSummary>(), b = deferred<DecisionSummary>();
  const hook = renderHook(() => useInbox(fake.client));
  await waitFor(() => expect(hook.result.current.state).toBe("ready"));
  const original = hook.result.current.inbox!.items[0]!, second = initial.items[1]!;
  fake.call.mockImplementationOnce(() => a.promise).mockImplementationOnce(() => b.promise);
  let one!: Promise<void>, two!: Promise<void>;
  act(() => { one = hook.result.current.act(original.decisionId, "ignore"); two = hook.result.current.act(second.decisionId, "exit_intent"); });
  const caught = one.catch(() => {});
  b.resolve({ ...second, action: { action: "exit_intent", note: null, actedAt: initial.asOf } });
  await act(() => two);
  a.reject(new RpcError("INTERNAL", "synthetic failure"));
  await act(() => caught);
  expect(hook.result.current.inbox!.items.find(d => d.decisionId === original.decisionId)).toBe(original);
  expect(hook.result.current.inbox!.processed[0]!.decisionId).toBe(second.decisionId);
});
test("inbox_refresh_cannot_undo_pending_or_just_completed_actions", async () => {
  const initial = pendingInbox(), fake = testClient(initial), write = deferred<DecisionSummary>(), stale = deferred<Inbox>();
  const hook = renderHook(() => useInbox(fake.client));
  await waitFor(() => expect(hook.result.current.state).toBe("ready"));
  const item = initial.items[0]!;
  fake.call.mockImplementationOnce(() => write.promise);
  let action!: Promise<void>, request!: Promise<void>;
  act(() => { action = hook.result.current.act(item.decisionId, "ignore"); });
  await act(async () => {});
  fake.call.mockImplementationOnce(() => stale.promise);
  act(() => { request = hook.result.current.refresh(); });
  write.resolve({ ...item, action: { action: "ignore", note: null, actedAt: initial.asOf } });
  await act(() => action);
  stale.resolve(initial);
  await act(() => request);
  expect(hook.result.current.inbox!.items).toHaveLength(2);
  expect(hook.result.current.inbox!.processed[0]!.action!.action).toBe("ignore");
});
test("inbox_focus_refresh_notification_validation_and_strictmode_cleanup", async () => {
  const fake = testClient();
  const hook = renderHook(() => useInbox(fake.client), { wrapper: ({ children }: { children: ReactNode }) => <StrictMode>{children}</StrictMode> });
  await waitFor(() => expect(hook.result.current.state).toBe("ready"));
  const count = fake.call.mock.calls.length;
  act(() => fake.emit("inbox.updated", { newItems: 1, pendingCount: "4" }));
  expect(fake.call.mock.calls).toHaveLength(count);
  act(() => fake.emit("inbox.updated", { newItems: 1, pendingCount: 999 }));
  await waitFor(() => expect(fake.call.mock.calls).toHaveLength(count + 1));
  expect(hook.result.current.inbox!.items).toHaveLength(3);
  act(() => window.dispatchEvent(new Event("focus")));
  await waitFor(() => expect(fake.call.mock.calls).toHaveLength(count + 2));
  act(() => refresh("today"));
  await waitFor(() => expect(fake.call.mock.calls).toHaveLength(count + 3));
  act(() => fake.emit("scan.finished", example<ScanRun>("scan.status", "done")));
  await waitFor(() => expect(fake.call.mock.calls).toHaveLength(count + 4));
  hook.unmount();
  expect([...fake.handlers.values()].every(group => group.size === 0)).toBe(true);
});
test("inbox_failed_refresh_retains_cached_data_and_no_cache_load_failure_is_error", async () => {
  const fake = testClient(), hook = renderHook(() => useInbox(fake.client));
  await waitFor(() => expect(hook.result.current.state).toBe("ready"));
  const previous = hook.result.current.inbox;
  fake.call.mockRejectedValueOnce(new RpcError("SOURCE_UNAVAILABLE", "offline"));
  await act(() => hook.result.current.refresh());
  expect(hook.result.current.inbox).toBe(previous);
  expect(hook.result.current.state).toBe("error");
  hook.unmount();
  const failure = testClient(); failure.call.mockRejectedValue(new RpcError("INTERNAL", "failure"));
  const initial = renderHook(() => useInbox(failure.client));
  await waitFor(() => expect(initial.result.current.state).toBe("error"));
  expect(initial.result.current.inbox).toBeNull();
});
