#!/usr/bin/env python3
"""从契约确定性生成类型；先验证全部输出，避免失败留下半成品。"""

from __future__ import annotations

import argparse
import json
import math
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED_HEADER = "/* Generated by scripts/gen_ts_types.py. Do not edit. */"
KINDS = {"null", "boolean", "string", "integer", "number", "object", "array"}
ANNOTATIONS = {"$schema", "title", "description"}
BOUNDS = {"minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum"}
SIZES = {"minLength", "maxLength", "minItems", "maxItems"}
KEYS = (
    ANNOTATIONS
    | BOUNDS
    | SIZES
    | {
        "$defs",
        "$ref",
        "type",
        "enum",
        "const",
        "properties",
        "required",
        "additionalProperties",
        "items",
        "uniqueItems",
        "pattern",
        "format",
        "anyOf",
        "oneOf",
        "allOf",
    }
)


class SchemaError(ValueError):
    pass


def require(condition, path, message):
    if not condition:
        raise SchemaError(f"{path}: {message}")


def pairs(items):
    result = {}
    for key, value in items:
        require(key not in result, key, "duplicate JSON key")
        result[key] = value
    return result


def load(path):
    try:
        return json.loads(
            path.read_text(encoding="utf-8"),
            object_pairs_hook=pairs,
            parse_constant=lambda value: require(
                False, str(path), "nonfinite " + value
            ),
        )
    except (ValueError, OSError) as exc:
        raise SchemaError(f"{path}: {exc}") from exc


def js(value, indent=None):
    return (
        json.dumps(value, ensure_ascii=False, indent=indent, allow_nan=False)
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def numeric(value):
    try:
        return type(value) in (int, float) and math.isfinite(value)
    except OverflowError:
        return False


def matches(value, kind):
    return {
        "null": value is None,
        "boolean": type(value) is bool,
        "string": isinstance(value, str),
        "number": numeric(value),
        "integer": numeric(value) and value == int(value),
        "object": isinstance(value, dict),
        "array": isinstance(value, list),
    }[kind]


class SchemaTypes:
    def __init__(self, types, prefix=""):
        self.types, self.prefix = types, prefix

    def reference(self, ref, path, active):
        require(isinstance(ref, str), path, "$ref must be string")
        filename, separator, pointer = ref.partition("#")
        require(
            separator
            and filename in ("", "types.schema.json")
            and pointer.startswith("/$defs/"),
            path,
            "unsupported $ref",
        )
        node, tokens = self.types, pointer[1:].split("/")
        for token in tokens:
            require(not re.search(r"~(?![01])", token), path, "invalid JSON pointer")
            token = token.replace("~1", "/").replace("~0", "~")
            require(
                isinstance(node, dict) and token in node, path, "unknown $ref " + ref
            )
            node = node[token]
        require(id(node) not in active, path, "circular $ref " + ref)
        rendered = self.render(node, path + " -> " + ref, active + (id(node),))
        if len(tokens) == 2:
            return self.prefix + tokens[1].replace("~1", "/").replace("~0", "~")
        return rendered

    def render(self, schema, path="schema", active=()):
        require(
            isinstance(schema, dict) and bool(schema), path, "expected nonempty schema"
        )
        require(
            not set(schema) - KEYS,
            path,
            "unsupported keywords: " + ", ".join(sorted(set(schema) - KEYS)),
        )
        for key in ANNOTATIONS & set(schema):
            require(isinstance(schema[key], str), path + "." + key, "expected string")
        kinds = schema.get("type", [])
        kinds = kinds if isinstance(kinds, list) else [kinds]
        require(
            all(isinstance(k, str) and k in KINDS for k in kinds), path, "invalid type"
        )
        require(
            len(kinds) == len(set(kinds)) and ("type" not in schema or bool(kinds)),
            path,
            "empty or duplicate type",
        )
        for key in BOUNDS & set(schema):
            require(
                numeric(schema[key]) and bool(set(kinds) & {"number", "integer"}),
                path + "." + key,
                "invalid numeric constraint",
            )
        for key in SIZES & set(schema):
            require(
                type(schema[key]) is int and schema[key] >= 0,
                path + "." + key,
                "invalid size constraint",
            )
        for low, high in (
            ("minimum", "maximum"),
            ("minLength", "maxLength"),
            ("minItems", "maxItems"),
        ):
            require(
                low not in schema or high not in schema or schema[low] <= schema[high],
                path,
                "inverted bounds",
            )
        if set(schema) & {"minLength", "maxLength", "pattern", "format"}:
            require("string" in kinds, path, "string constraints require string")
        if "pattern" in schema:
            require(isinstance(schema["pattern"], str), path, "invalid pattern")
            try:
                re.compile(schema["pattern"])
            except re.error as exc:
                raise SchemaError(path + ": invalid pattern") from exc
        if "format" in schema:
            require(
                schema["format"] in ("date", "date-time"), path, "unsupported format"
            )
        if set(schema) & {"properties", "required", "additionalProperties"}:
            require("object" in kinds, path, "object constraints require object")
        if set(schema) & {"items", "minItems", "maxItems", "uniqueItems"}:
            require("array" in kinds, path, "array constraints require array")
        if "uniqueItems" in schema:
            require(type(schema["uniqueItems"]) is bool, path, "invalid uniqueItems")
        definitions = schema.get("$defs", {})
        require(isinstance(definitions, dict), path + ".$defs", "expected object")
        for name, child in definitions.items():
            self.render(child, path + ".$defs." + name, active)
        parts = []
        if "$ref" in schema:
            parts.append(self.reference(schema["$ref"], path + ".$ref", active))
        for keyword in ("anyOf", "oneOf", "allOf"):
            if keyword in schema:
                branches = schema[keyword]
                require(
                    isinstance(branches, list) and bool(branches),
                    path,
                    "empty or invalid " + keyword,
                )
                children = [
                    self.render(s, f"{path}.{keyword}[{i}]", active)
                    for i, s in enumerate(branches)
                ]
                parts.append(
                    "(" + (" & " if keyword == "allOf" else " | ").join(children) + ")"
                )
        basic = []
        for kind in kinds:
            if kind == "object":
                props = schema.get("properties", {})
                required = schema.get("required", [])
                require(
                    isinstance(props, dict)
                    and isinstance(required, list)
                    and all(isinstance(k, str) for k in required),
                    path,
                    "invalid properties/required",
                )
                require(
                    len(required) == len(set(required)) and set(required) <= set(props),
                    path,
                    "unknown or duplicate required property",
                )
                fields = [
                    "{}{}: {};".format(
                        js(k),
                        "" if k in required else "?",
                        self.render(v, path + ".properties." + k, active),
                    )
                    for k, v in props.items()
                ]
                extra = schema.get("additionalProperties", True)
                require(
                    type(extra) is bool or isinstance(extra, dict),
                    path,
                    "invalid additionalProperties",
                )
                obj = "{ " + " ".join(fields) + " }" if fields else ""
                if extra is not False:
                    record = "Record<string, %s>" % (
                        "unknown"
                        if extra is True
                        else self.render(extra, path + ".additionalProperties", active)
                    )
                    obj = "(" + obj + " & " + record + ")" if obj else record
                basic.append(obj or "Record<string, never>")
            elif kind == "array":
                require("items" in schema, path, "array requires items")
                basic.append(
                    "Array<"
                    + self.render(schema["items"], path + ".items", active)
                    + ">"
                )
            else:
                basic.append("number" if kind == "integer" else kind)
        if basic:
            parts.append(basic[0] if len(basic) == 1 else "(" + " | ".join(basic) + ")")
        for keyword in ("enum", "const"):
            if keyword in schema:
                values = schema[keyword] if keyword == "enum" else [schema[keyword]]
                require(isinstance(values, list) and bool(values), path, "invalid enum")
                require(
                    len({js(v) for v in values}) == len(values), path, "duplicate enum"
                )
                require(
                    not kinds or all(any(matches(v, k) for k in kinds) for v in values),
                    path,
                    "literal contradicts type",
                )
                literal = " | ".join(js(v) for v in values)
                if basic and len(parts) == 1:
                    parts = [literal]
                else:
                    parts.append("(" + literal + ")" if len(values) > 1 else literal)
        require(bool(parts), path, "schema does not constrain a type")
        return parts[0] if len(parts) == 1 else "(" + " & ".join(parts) + ")"


def metadata(contracts):
    index = load(contracts / "index.json")
    require(isinstance(index, dict), "index.json", "expected object")
    for field in ("methods", "notifications"):
        path = "index.json." + field
        names = index.get(field)
        require(
            isinstance(names, list) and bool(names), path, "expected nonempty array"
        )
        require(
            all(
                isinstance(name, str)
                and re.fullmatch(r"[a-zA-Z]+(?:\.[a-zA-Z]+)+", name)
                for name in names
            ),
            path,
            "invalid RPC name",
        )
        require(len(names) == len(set(names)), path, "duplicate RPC names")
    errors = load(contracts / "errors.json")
    require(isinstance(errors, dict), "errors.json", "expected object")
    codes = errors.get("codes")
    require(
        isinstance(codes, dict) and bool(codes),
        "errors.json.codes",
        "expected nonempty object",
    )
    for code, item in codes.items():
        path = "errors.json.codes." + code
        require(re.fullmatch(r"[A-Z][A-Z0-9_]*", code), path, "invalid error code")
        require(isinstance(item, dict), path, "expected object")
        require(
            type(item.get("retryable")) is bool, path + ".retryable", "expected boolean"
        )
    return index, codes


def generate(contracts):
    index, codes = metadata(contracts)
    types = load(contracts / "types.schema.json")
    require(
        isinstance(types, dict) and isinstance(types.get("$defs"), dict),
        "types.schema.json",
        "missing $defs",
    )
    require(
        set(types) <= {"$schema", "$defs"},
        "types.schema.json",
        "unsupported root keywords",
    )
    require(
        "$schema" not in types or isinstance(types["$schema"], str),
        "types.schema.json.$schema",
        "expected string",
    )
    local, external = SchemaTypes(types), SchemaTypes(types, "Types.")
    declarations = []
    for name, schema in types["$defs"].items():
        require(
            re.fullmatch(r"[A-Z][A-Za-z0-9]*", name),
            name,
            "invalid TypeScript type name",
        )
        value = local.render(schema, "types.schema.json.$defs." + name)
        if value.startswith("{ "):
            declarations.append(f"export interface {name} {value}")
        else:
            declarations.append(f"export type {name} = {value};")
    declarations.append(
        "export type ErrorCode = " + " | ".join(js(c) for c in codes) + ";"
    )
    methods, examples, timeouts = [], {}, {}
    for name in index["methods"]:
        item = load(contracts / "methods" / (name + ".json"))
        require(item["method"] == name, name, "method mismatch")
        params = external.render(item["params"], name + ".params")
        result = external.render(item["result"], name + ".result")
        methods.append(f"  {js(name)}: {{ params: {params}; result: {result} }};")
        examples[name], timeouts[name] = item["examples"], item["timeoutMs"]
    notices, mock_notices = load(contracts / "notifications.json"), {}
    notice_fields = []
    for name in index["notifications"]:
        notice_fields.append(
            "  {}: {};".format(
                js(name), external.render(notices[name]["params"], name + ".params")
            )
        )
        mock_notices[name] = notices[name]["example"]
    method_text = (
        'import type * as Types from "./types";\n\nexport interface MethodMap {\n'
        + "\n".join(methods)
        + "\n}\n"
    )
    method_text += 'export type MethodName = keyof MethodMap;\nexport type ParamsOf<M extends MethodName> = MethodMap[M]["params"];\nexport type ResultOf<M extends MethodName> = MethodMap[M]["result"];\n'
    method_text += (
        "export interface NotificationMap {\n"
        + "\n".join(notice_fields)
        + "\n}\nexport type NotificationName = keyof NotificationMap;\nexport type ParamsOfNotification<N extends NotificationName> = NotificationMap[N];\n"
    )
    method_text += "export const METHOD_TIMEOUTS = " + js(timeouts, 2) + " as const;\n"
    method_text += (
        "export const ERROR_RETRYABLE = "
        + js({c: item["retryable"] for c, item in codes.items()}, 2)
        + " as const;\n"
    )
    method_text += (
        "export const NOTIFICATION_NAMES = "
        + js(index["notifications"])
        + " as const;\n"
    )
    mock_text = (
        "export const MOCK_EXAMPLES = "
        + js(examples, 2)
        + " as const;\n\nexport const MOCK_NOTIFICATIONS = "
        + js(mock_notices, 2)
        + " as const;\n"
    )
    return {
        name: (GENERATED_HEADER + "\n" + text).encode("utf-8")
        for name, text in {
            "types.ts": "\n\n".join(declarations) + "\n",
            "methods.ts": method_text,
            "mock-data.ts": mock_text,
        }.items()
    }


def publish(out, outputs):
    out.mkdir(parents=True, exist_ok=True)
    # 临时文件与目标同盘；只有全部文件写完才替换，避免写入截断旧文件。
    with tempfile.TemporaryDirectory(dir=out, prefix=".gen-") as temp:
        staged = Path(temp)
        for name, value in outputs.items():
            (staged / name).write_bytes(value)
        previous = {
            name: (out / name).read_bytes() if (out / name).exists() else None
            for name in outputs
        }
        replaced = []
        try:
            for name in outputs:
                os.replace(staged / name, out / name)
                replaced.append(name)
        except OSError:
            for name in replaced:
                if previous[name] is None:
                    (out / name).unlink()
                else:
                    (staged / name).write_bytes(previous[name])
                    os.replace(staged / name, out / name)
            raise


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--contracts", type=Path, default=ROOT / "contracts")
    parser.add_argument(
        "--out", type=Path, default=ROOT / "apps/desktop/src/rpc/generated"
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        contracts, out = args.contracts.resolve(), args.out.resolve()
        require(
            out != contracts
            and contracts not in out.parents
            and out not in contracts.parents,
            str(out),
            "output cannot overwrite contracts",
        )
        outputs = generate(contracts)
        if args.check:
            drift = [
                name
                for name, value in outputs.items()
                if not (out / name).is_file() or (out / name).read_bytes() != value
            ]
            if drift:
                print("generated TypeScript differs: " + ", ".join(drift))
                return 1
            print("generated TypeScript is up to date")
        else:
            publish(out, outputs)
            print("generated TypeScript: " + ", ".join(outputs))
        return 0
    except (
        SchemaError,
        OSError,
        ValueError,
        KeyError,
        TypeError,
        AttributeError,
        RecursionError,
    ) as exc:
        print(str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
